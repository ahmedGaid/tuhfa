/**
 * Writes a module's data back to its folder as typed TS literals, one file per part
 * (contracts/content-module.md). Used by extract-prototype.ts and locate-ayah.ts so both produce
 * byte-identical layout. Prettier formats the result.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Module } from '../../src/content/schema.ts';

const HEADER = `// Content data — generated by scripts/extract-prototype.ts, refs by scripts/locate-ayah.ts.
// Text is EXTRACTED from the prototype, never retyped. Quran text must match Tanzil (npm run validate).
// Hand-fixes are fine; record why in CONTENT_NOTES.md.
`;

const lit = (v: unknown) => JSON.stringify(v, null, 2);

function part(type: string, name: string, value: unknown) {
  return `${HEADER}import type { ${type.replace('[]', '')} } from '../../schema.ts';\n\nexport const ${name}: ${type} = ${lit(value)};\n`;
}

export function emitModule(dir: string, m: Module): string[] {
  mkdirSync(dir, { recursive: true });
  const files: Record<string, string> = {
    'categories.ts': part('Category[]', 'categories', m.categories),
    'concepts.ts': part('Concept[]', 'concepts', m.concepts),
    'units.ts': part('Unit[]', 'units', m.units),
    'lessons.ts': part('Lesson[]', 'lessons', m.lessons),
    'tree.ts': part('TreeNode', 'tree', m.tree),
    'questions.ts': part('Question[]', 'questions', m.questions ?? []),
    'spot.ts': part('SpotItem[]', 'spot', m.spot ?? []),
    'extras.ts': part('Extras', 'extras', m.extras ?? {}),
    'index.ts': `${HEADER}import type { Module } from '../../schema.ts';
import { categories } from './categories.ts';
import { concepts } from './concepts.ts';
import { extras } from './extras.ts';
import { lessons } from './lessons.ts';
import { questions } from './questions.ts';
import { spot } from './spot.ts';
import { tree } from './tree.ts';
import { units } from './units.ts';

const module: Module = {
  id: ${lit(m.id)},
  title: ${lit(m.title)},
  rulings: ${lit(m.rulings)},
  prompts: ${lit(m.prompts)},
  rank: ${lit(m.rank)},
  categories,
  concepts,
  units,
  lessons,
  tree,
  questions,
  spot,
  extras,
};

export default module;
`,
  };
  const paths = Object.entries(files).map(([name, text]) => {
    const p = join(dir, name);
    writeFileSync(p, text);
    return p;
  });
  formatFiles(paths);
  return paths;
}

/** Run the repo's Prettier on generated files so `format:check` stays green. */
export function formatFiles(paths: string[]) {
  execFileSync(
    process.execPath,
    ['node_modules/prettier/bin/prettier.cjs', '--write', '--log-level=warn', ...paths],
    {
      stdio: 'inherit',
    },
  );
}
